"""`glue` for whole classes: one JNI module per class.

For every *supported* method of the class (static, with JNI-supported types --
validated by ``jni.plan``, so unsupported types raise the same clear errors),
generates into ``out_dir``:

- ``<Cls>Native.java``: one ``static native`` declaration per kernel method.
- ``kernels_jni.cpp``: ONE combined file with a ``kernel_<name>`` helper +
  ``TODO(agent)`` translation slot and a ``JNIEXPORT`` wrapper per method.
- ``CMakeLists.txt``: builds ``libkernels.so``.

The per-method C++ fragments come from ``jni.render_cpp`` (split on its
stable markers and reassembled into one translation unit); the Java file is
assembled from ``jni.plan`` data. Methods that cannot be glued (constructors,
instance methods, unsupported types) are listed in a comment in the generated
C++ -- no fallback dispatcher (owned by another workstream).
"""

from __future__ import annotations

from pathlib import Path

from . import java_ast as J
from . import jni


def _split_cpp(rendered: str) -> tuple[str, str, str]:
    """Split one ``jni.render_cpp()`` output into (preamble, helper, wrapper).

    Relies on render_cpp's stable markers: the translated-kernel comment, the
    ``extern "C" {`` opener and the ``} // extern "C"`` closer.
    """
    helper_marker = "// ---- Translated kernel (filled in by the agent) ----"
    extern_open = 'extern "C" {'
    extern_close = '} // extern "C"'
    hi = rendered.index(helper_marker)
    eo = rendered.index(extern_open)
    ec = rendered.index(extern_close)
    preamble = rendered[:hi]
    helper = rendered[hi:eo]
    wrapper = rendered[eo + len(extern_open) : ec]
    return preamble, helper, wrapper


def _render_java(
    plans: list[jni.GluePlan], skipped: list[str], class_qualname: str
) -> str:
    native_class = (
        plans[0].native_class if plans else class_qualname.rsplit(".", 1)[-1] + "Native"
    )
    lines = [
        "// Generated by kernel-port. Do not hand-edit: regenerate with",
        f"//   kernel-port glue --class {class_qualname}",
        f"// JNI bindings for {class_qualname}",
        "",
        f"public class {native_class} {{",
        "    static {",
        '        System.loadLibrary("kernels");',
        "    }",
        "",
    ]
    for p in plans:
        m = p.method
        java_params = ", ".join(f"{prm.jtype} {prm.name}" for prm in m.params)
        lines.append(f"    public static native {m.jtype} {m.name}({java_params});")
    for s in skipped:
        lines.append(f"    // not gluable in v0.1: {s}")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def _render_cpp(
    plans: list[jni.GluePlan], skipped: list[str], class_qualname: str
) -> str:
    if not plans:
        lines = [
            "// Generated by kernel-port. Do not hand-edit: regenerate with",
            f"//   kernel-port glue --class {class_qualname}",
            f"// No gluable methods in {class_qualname}.",
            "",
            "#include <jni.h>",
            "",
        ]
        for s in skipped:
            lines.append(f"// not gluable in v0.1: {s}")
        return "\n".join(lines)
    preamble, _, _ = _split_cpp(jni.render_cpp(plans[0]))
    chunks = [preamble]
    helpers: list[str] = []
    wrappers: list[str] = []
    for p in plans:
        _, helper, wrapper = _split_cpp(jni.render_cpp(p))
        helpers.append(helper)
        wrappers.append(wrapper)
    chunks.extend(helpers)
    chunks.append('extern "C" {\n')
    chunks.extend(wrappers)
    chunks.append('} // extern "C"\n')
    if skipped:
        chunks.append("\n// Not gluable in v0.1 (no fallback dispatcher):\n")
        for s in skipped:
            chunks.append(f"//   - {s}\n")
    return "".join(chunks)


def generate_class(
    repo: J.JavaRepo, class_qualname: str, out_dir: str | Path
) -> dict[str, Path]:
    """Write combined JNI glue for a class; return {kind: path}."""
    cls = repo.classes.get(class_qualname)
    if cls is None:
        raise ValueError(f"class not found: {class_qualname}")
    plans: list[jni.GluePlan] = []
    skipped: list[str] = []
    for m in cls.all_methods:
        if m.is_constructor:
            skipped.append(f"{m.qualname} (constructor)")
            continue
        try:
            plans.append(jni.plan(m))
        except ValueError as e:
            # same clear errors as single-method glue (unsupported types, ...)
            skipped.append(f"{m.qualname} ({e})")
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    native_class = plans[0].native_class if plans else cls.name + "Native"
    files = {
        "java": out / f"{native_class}.java",
        "cpp": out / "kernels_jni.cpp",
        "cmake": out / "CMakeLists.txt",
    }
    files["java"].write_text(
        _render_java(plans, skipped, class_qualname), encoding="utf-8"
    )
    files["cpp"].write_text(
        _render_cpp(plans, skipped, class_qualname), encoding="utf-8"
    )
    files["cmake"].write_text(jni.render_cmake(), encoding="utf-8")
    return files
