"""Tests for kernel_port.report.render_html."""

import pytest

from kernel_port.report import render_html


def full_report() -> dict:
    return {
        "title": "kernel-port pipeline report",
        "generated_at": "2026-10-17T22:00:00",
        "method": "com.example.MathUtils.dotProduct",
        "status": "success",
        "purity": {
            "pure": True,
            "reasons": ["no static field access", "no I/O calls"],
        },
        "candidates": [
            {"name": "dotProduct", "kind": "method", "score": 0.94, "pure": True},
            {"name": "MathUtils", "kind": "class", "score": 0.71, "pure": False},
        ],
        "verify": {
            "passed": 1000,
            "failed": 0,
            "skipped": 2,
            "boundary_passed": 12,
            "boundary_failed": 0,
        },
        "bench": {
            "java_per_call_ns": 1880.5,
            "jni_per_call_ns": 1000.0,
            "speedup": 1.88,
            "jni_overhead_ns": 120.0,
            "per_size": [
                {"size": 100, "speedup": 0.92},
                {"size": 1000, "speedup": 1.88},
                {"size": 10000, "speedup": 2.41},
            ],
        },
        "winner": "candidate-b",
        "verdict": "worth porting: 1.88x faster",
    }


# ---------------------------------------------------------------------------
# full report
# ---------------------------------------------------------------------------


def test_full_report_contains_key_content():
    out = render_html(full_report())
    assert "com.example.MathUtils.dotProduct" in out
    assert "badge-green" in out  # status badge
    assert "worth porting: 1.88x faster" in out
    assert "<svg" in out  # hand-rolled charts
    assert "speedup vs input size" in out
    assert "generated by kernel-port v0.3.0" in out


def test_full_report_html5_structure():
    out = render_html(full_report())
    assert out.startswith("<!DOCTYPE html>")
    assert "<html" in out and "</html>" in out
    assert "<head>" in out and "<style>" in out and "</style>" in out
    assert "<body>" in out and "</body>" in out


def test_no_external_urls_in_output():
    out = render_html(full_report())
    assert "http" not in out
    assert "www." not in out
    assert 'src="' not in out and "href=" not in out


def test_user_content_is_escaped():
    report = full_report()
    report["purity"]["reasons"] = ["<script>alert('xss')</script>"]
    report["candidates"] = [
        {"name": "<img src=x onerror=1>", "kind": "method", "score": 1.0, "pure": True}
    ]
    report["verdict"] = "worth porting & <b>faster</b>"
    out = render_html(report)
    assert "<script>" not in out
    assert "&lt;script&gt;alert(&#x27;xss&#x27;)&lt;/script&gt;" in out
    assert "&lt;img src=x onerror=1&gt;" in out
    assert "worth porting &amp; &lt;b&gt;faster&lt;/b&gt;" in out


def test_two_bench_bars_and_overhead():
    out = render_html(full_report())
    assert out.count("<rect") >= 2  # Java + JNI bars (plus per_size bars)
    assert "JNI overhead" in out
    assert "120.0" in out


