def test_minimal_report_renders_without_crashing():
    out = render_html({})
    assert "<!DOCTYPE html>" in out
    assert "n/a" in out  # missing sections render as n/a


def test_none_and_partial_sections():
    out = render_html(
        {
            "status": "rejected",
            "purity": None,
            "candidates": [{"name": "x"}],  # missing kind/score/pure
            "verify": {"failed": 3},  # missing the rest
            "bench": {},
            "verdict": "",
        }
    )
    assert "badge-red" in out
    assert "n/a" in out
    assert 'class="fail"' in out  # failed=3 highlighted


def test_non_dict_report():
    out = render_html(None)  # type: ignore[arg-type]
    assert "<!DOCTYPE html>" in out


