def test_per_size_chart_absent_without_data():
    out = render_html(full_report() | {"bench": {"java_per_call_ns": 5.0, "jni_per_call_ns": 10.0}})
    assert "speedup vs input size" not in out
    assert "<svg" in out  # the Java-vs-JNI bars chart is still there


def test_per_size_chart_present_with_data():
    out = render_html(full_report())
    assert "speedup vs input size" in out
    # break-even reference line and sub-1x red bar for n=100 (0.92x)
    assert 'stroke-dasharray="5,4"' in out
    assert 'fill="#ef4444"' in out
    assert 'fill="#10b981"' in out


def test_bench_chart_missing_data_graceful():
    out = render_html({"bench": {"speedup": None}})
    assert "<!DOCTYPE html>" in out
    assert "no benchmark data" in out


