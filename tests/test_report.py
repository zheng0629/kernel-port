def test_verdict_banner_green_when_worth_porting():
    out = render_html({"verdict": "worth porting: 1.88x faster"})
    assert "verdict-good" in out


def test_verdict_banner_yellow_when_not_worth_porting():
    out = render_html({"verdict": "not worth porting: JNI overhead dominates"})
    assert "verdict-bad" in out


def test_verdict_derived_from_speedup():
    good = render_html({"bench": {"speedup": 2.0}})
    assert "verdict-good" in good
    bad = render_html({"bench": {"speedup": 0.5}})
    assert "verdict-bad" in bad


def test_purity_impure_panel():
    out = render_html({"purity": {"pure": False, "reasons": ["writes static field"]}})
    assert "purity-red" in out
    assert "NOT PURE" in out
    assert "writes static field" in out
