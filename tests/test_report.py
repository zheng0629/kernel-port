@pytest.mark.parametrize(
    "status,css",
    [
        ("success", "badge-green"),
        ("verify_failed", "badge-red"),
        ("rejected", "badge-red"),
        ("cache_hit", "badge-blue"),
        ("awaiting_translation", "badge-gray"),
    ],
)
def test_status_badge_colors(status, css):
    out = render_html({"status": status})
    assert css in out


def test_verify_failed_status_renders_red():
    out = render_html(
        {"status": "verify_failed", "verify": {"passed": 950, "failed": 50}}
    )
    assert "badge-red" in out
    assert 'class="fail"' in out


